test('outbound endpoints require public HTTPS and DNS pinning rejects local/special addresses', async () => {
  for (const ip of ['127.0.0.1', '10.0.0.1', '192.168.1.1', '169.254.169.254', '::1', '::ffff:127.0.0.1', '100.64.0.1', 'fc00::1', 'fe80::6', '0.0.0.0']) assert.equal(isPublicAddress(ip), false, ip);
  assert.equal(isPublicAddress('8.8.8.8'), true);
  assert.equal(isPublicAddress('2606:4700::1111'), true);
  for (const url of ['http://mcp.example.test', 'https://127.0.0.1', 'https://[::ffff:127.0.0.1]/mcp', 'https://service.local', 'https://mcp.example:9443', 'https://key@public.example', 'https://public.example?token=secret']) assert.throws(() => externalUrl(url), { status: 400 });
  assert.equal(externalUrl('http://127.0.0.1:11434/v1', { allowLocal: true }).port, '11434');
  assert.equal(externalUrl('https://mcp.example.test/remote').pathname, '/remote');
  const dns = (rows) => new Promise((resolve, reject) => safeResolver('service.example', { all: true }, (error, result) => error ? reject(error) : resolve(result), (_hostname, options, done) => { assert.equal(options.all, true); done(null, rows); }));
  await assert.rejects(dns([{ address: '8.8.8.8', family: 4 }, { address: '127.0.0.1', family: 4 }]), { code: 'EHOSTUNREACH' });
  assert.deepEqual(await dns([{ address: '8.8.8.8', family: 4 }]), [{ address: '8.8.8.8', family: 4 }]);
});

test('MCP token rotation, Buffer metadata and expiring media links', () => {
  const store = { seal: (value) => `sealed-${value}`, state: { bufferLinks: [] } };
  const initial = mcpInput({ name: 'Personal tools', kind: 'remote', url: 'https://example.test/mcp', token: 'fake-token' }, null, store);
  assert.equal(mcpInput({ ...initial, name: 'Renamed' }, initial, store).secret, 'sealed-fake-token');
  assert.equal(mcpInput({ ...initial, url: 'https://another.example/mcp' }, initial, store).secret, '');
  assert.throws(() => mcpInput({ kind: 'remote', url: 'https://mcp.buffer.com/MCP', token: 'fake-token' }, null, store), { status: 400 });
  assert.equal(mcpInput({ name: 'Buffer', kind: 'remote', url: 'https://mcp.buffer.com/mcp', token: 'fake-token' }, null, store).kind, 'buffer');
  const clip = { title: 'Fixture clip', id: 'clip-1' }, job = { id: randomUUID() };
  const make = (input) => bufferPostArgs({ clip, input: { channelId: mockChannelId, service: 'youtube', ...input }, mediaUrl: 'https://media.example.test/video.mp4' });
  assert.throws(() => make({ consent: false }), { status: 400 });
  assert.throws(() => make({ consent: true }), { status: 400 });
  const youtube = make({ consent: true, madeForKids: false, saveToDraft: false, mode: 'shareNow' });
  assert.equal(youtube.saveToDraft, true);
  assert.equal(youtube.dueAt, undefined);
  assert.equal(youtube.metadata.youtube.privacy, 'private');
  assert.equal(youtube.metadata.youtube.notifySubscribers, false);
  assert.equal(make({ consent: true, service: 'instagram' }).metadata.instagram.type, 'reel');
  const entry = allocateVideoLink(store, requestOrigin, job, clip);
  const token = new URL(entry.url).pathname.split('/').pop().slice(0, -4);
  assert.equal(videoLink(store, token).jobId, job.id);
  assert.ok(!JSON.stringify(store.state).includes(token));
  assert.equal(videoLink(store, 'short'), null);
  entry.entry.expires = 0;
  assert.equal(videoLink(store, token), undefined);
});

test('Streamable HTTP discovery, approved tool calls, and Buffer draft-only delivery with mock responses', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'curiousity-mcp-api-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const store = createStore(root), jobId = randomUUID();
  const now = new Date().toISOString();
  const clips = ['clip-1', 'clip-2', 'clip-3'].map((id) => ({ id, title: `Reviewed ${id}`, duration: 10 }));
  for (const clip of clips) {
    const folder = join(root, 'projects', jobId, clip.id);
    await mkdir(folder, { recursive: true });
    await writeFile(join(folder, 'video.mp4'), 'fixture mp4 body');
  }
  store.state.jobs.push({ id: jobId, title: 'Private fixture', status: 'ready', options: { demo: false }, clips, createdAt: now, updatedAt: now });
  store.save();
  const trace = join(root, 'trace.jsonl');
  await writeFile(trace, '');
  const engine = await startEngine(t, { imports: ['test/fixtures/mcp-network.mjs'], env: { DATA_DIR: root, ADMIN_EMAIL: exampleAdmin.email, ADMIN_PASSWORD: exampleAdmin.password, PUBLIC_ORIGIN: requestOrigin, FIXTURE_MCP_TRACE: trace, ENABLE_LEGACY_INTEGRATION_API: 'true' } });
  const admin = engine.agent(), member = engine.agent();
  assert.equal((await admin.signin()).status, 200);
  assert.equal((await member.signup('second@example.test')).status, 201);
  async function json(res, status = 200) { const body = await res.json(); assert.equal(res.status, status, JSON.stringify(body)); return body; }
  const remote = await json(await admin.post('/mcp', { kind: 'remote', name: 'Remote fixture', url: 'https://mcp.example.test/mcp', token: 'fixture-secret' }), 201);
  const listing = await json(await admin.post(`/mcp/${remote.id}/inspect`));
  assert.equal(listing.serverName, 'Remote fixture');
  assert.deepEqual(listing.tools.map((tool) => tool.name), ['hello']);
  const run = (approved) => admin.post(`/mcp/${remote.id}/run`, { name: 'hello', arguments: { name: 'Ada' }, approved });
  assert.equal((await run(false)).status, 400);
  assert.deepEqual(await json(await run(true)), { output: 'Hello Ada; Bearer [redacted]', isError: false });
  assert.equal((await member.post(`/mcp/${remote.id}/inspect`)).status, 404);
  const buffer = await json(await admin.post('/mcp', { kind: 'buffer', token: 'fixture-buffer-key' }), 201);
  const tools = await json(await admin.post(`/mcp/${buffer.id}/inspect`));
  assert.equal(tools.tools.find((item) => item.name === 'create_post').runnable, false);
  assert.equal((await admin.post(`/mcp/${buffer.id}/run`, { name: 'create_post', arguments: { saveToDraft: false }, approved: true })).status, 403);
  assert.deepEqual(await json(await admin.post(`/mcp/${buffer.id}/organizations`)), [{ id: mockOrgId, name: 'Fixture workspace' }]);
  assert.deepEqual(await json(await admin.post(`/mcp/${buffer.id}/channels`, { organizationId: mockOrgId })), [{ id: mockChannelId, name: 'Fixture Instagram', service: 'instagram', reminder: false }]);
  const route = (i) => `/projects/${jobId}/clips/clip-${i}/buffer`;
  const args = { profileId: buffer.id, organizationId: mockOrgId, channelId: mockChannelId, service: 'instagram', consent: true, mediaMode: 'link', description: 'Reviewed post', saveToDraft: false, mode: 'shareNow' };
  assert.equal((await member.post(route(1), args)).status, 404);
  assert.equal((await admin.post(route(1), { ...args, consent: false })).status, 400);
  assert.equal((await admin.post(route(1), { ...args, mediaMode: 'external', mediaUrl: 'https://127.0.0.1/private' })).status, 400);
  const rejected = await json(await admin.post(route(1), { ...args, service: 'tiktok' }));
  assert.equal(rejected.clips[0].bufferDraft.state, 'failed');
  assert.equal(await readFile(trace, 'utf8'), '');
  const saved = await json(await admin.post(route(1), args));
  assert.equal(saved.clips[0].bufferDraft.state, 'draft');
  assert.equal(saved.clips[0].bufferDraft.id, mockPostId);
  assert.equal((await admin.post(route(1), args)).status, 409);
  const [sent] = (await readFile(trace, 'utf8')).trim().split('\n').map(JSON.parse);
  assert.equal(sent.saveToDraft, true);
  assert.equal(sent.mode, 'addToQueue');
  assert.equal(sent.text, 'Reviewed post');
  const target = new URL(sent.assets[0].video.url);
  assert.equal(target.origin, requestOrigin);
  assert.match(target.pathname, /^\/media\/buffer\/[\w-]+\.mp4$/);
  const file = await fetch(`${engine.url}${target.pathname}`, { headers: { Range: 'bytes=0-6' } });
  assert.equal(file.status, 206);
  assert.equal(await file.text(), 'fixture');
  assert.equal((await member.request(`/projects/${jobId}/clips/clip-1/video.mp4`)).status, 404);
  const token = target.pathname.split('/').at(-1).split('.')[0];
  assert.doesNotMatch(await readFile(join(root, 'workspace.json'), 'utf8'), new RegExp(token));
  const missing = await json(await admin.post('/mcp', { kind: 'buffer', token: 'fixture-denied' }), 201);
  assert.equal((await json(await admin.post(route(2), { ...args, profileId: missing.id }))).clips[1].bufferDraft.state, 'failed');
  const offline = await json(await admin.post('/mcp', { kind: 'buffer', token: 'fixture-unconfirmed' }), 201);
  const uncertain = await json(await admin.post(route(3), { ...args, profileId: offline.id, mediaMode: 'external', mediaUrl: 'https://files.example.test/movie.mp4' }));
  assert.equal(uncertain.clips[2].bufferDraft.state, 'unconfirmed');
  assert.equal((await admin.post(route(3), args)).status, 409);
  assert.equal((await readFile(trace, 'utf8')).trim().split('\n').length, 2);
  assert.equal((await admin.request(`/projects/${jobId}`, { method: 'DELETE' })).status, 204);
  assert.equal((await fetch(`${engine.url}${target.pathname}`)).status, 404);
});
